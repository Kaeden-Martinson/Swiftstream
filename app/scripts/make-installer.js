// Writes build/installer.nsh, which electron-builder includes in the Windows installer: installing puts
// <install dir>\resources\cli (swiftstream.exe and sws.cmd) on the user's PATH, uninstalling takes it off,
// and every install (updates too) makes sure the desktop shortcut is there.
// The PowerShell runs as -EncodedCommand so no quoting can break between NSIS, cmd and PowerShell.
import fs from 'node:fs';
import path from 'node:path';

const out = path.join(path.dirname(import.meta.dirname), 'build', 'installer.nsh');

// Reads and writes the raw registry value so entries like %USERPROFILE%\bin stay unexpanded.
const script = (mode) => `
$d = $env:SWIFTSTREAM_CLI_DIR
$k = 'HKCU:\\Environment'
$p = (Get-Item $k).GetValue('Path', '', 'DoNotExpandEnvironmentNames')
$parts = @($p -split ';' | Where-Object { $_ -and ($_.TrimEnd('\\') -ne $d.TrimEnd('\\')) })
${mode === 'add' ? '$parts += $d' : ''}
Set-ItemProperty -Path $k -Name Path -Value ($parts -join ';') -Type ExpandString
# Tell Windows the environment changed, so new terminals see it without signing out.
[Environment]::SetEnvironmentVariable('SWIFTSTREAM_PATH_REFRESH', '1', 'User')
[Environment]::SetEnvironmentVariable('SWIFTSTREAM_PATH_REFRESH', $null, 'User')
`;
const encoded = (mode) => Buffer.from(script(mode), 'utf16le').toString('base64');
const run = (mode) => `  System::Call 'Kernel32::SetEnvironmentVariable(t "SWIFTSTREAM_CLI_DIR", t "$INSTDIR\\resources\\cli")'
  nsExec::Exec 'powershell.exe -NoProfile -NonInteractive -ExecutionPolicy Bypass -EncodedCommand ${encoded(mode)}'`;

fs.writeFileSync(
  out,
  `; Generated by scripts/make-installer.js. Puts the swiftstream command on PATH and keeps the desktop shortcut.
!macro customInstall
${run('add')}
  ; electron-builder only creates the desktop shortcut on a first install; bring it back on updates too.
  \${ifNot} \${FileExists} "$DESKTOP\\Swiftstream.lnk"
    CreateShortCut "$DESKTOP\\Swiftstream.lnk" "$INSTDIR\\Swiftstream.exe" "" "$INSTDIR\\Swiftstream.exe" 0
    ClearErrors
    WinShell::SetLnkAUMI "$DESKTOP\\Swiftstream.lnk" "\${APP_ID}"
    System::Call 'Shell32::SHChangeNotify(i 0x8000000, i 0, i 0, i 0)'
  \${endIf}
!macroend

!macro customUnInstall
${run('remove')}
!macroend
`,
);
console.log(`wrote ${out}`);
